export function jobGuideFor(employee: RosterEmployee) {
  const exact = guides[employee.jobTitle];
  if (exact) return exact;
  if (employee.jobTitle.includes("مختص") && employee.department === "المبيعات") return guides["مختص المبيعات"];
  return guides.default;
}
